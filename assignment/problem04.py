'''
설명: 10개의 정수가 들어 있는 리스트에서 짝수만 화면에 출력하고, 짝수가 총 몇 개인지 개수를 세어 출력하세요.
주어지는 리스트: numbers = [12, 7, 19, 20, 33, 42, 8, 15, 26, 31]
힌트: 개수를 세는 변수(count = 0)를 만들고, for문 안에서 if num % 2 == 0: 일 때마다 count = count + 1을 합니다.
출력 예시:
짝수: 12
짝수: 20
짝수: 42
짝수: 8
짝수: 26
총 짝수 개수: 5개
'''

numbers = [12, 7, 19, 20, 33, 42, 8, 15, 26, 31]
count = 0
for num in numbers:
    if num % 2 == 0:
        count += 1
        print("짝수:", num)
print("총 짝수 갯수:", count,"개")